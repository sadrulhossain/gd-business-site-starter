// Post-build step for the static export (run after `next build`, see package.json "build").
//   1. out/404.html becomes the localised 404 page (header, footer, text) instead of Next's bare default.
//   2. The default-language tree out/<default>/ moves to the root, so the default language has no URL prefix.
//   3. out/_redirects.portal sends /<default>/* to /* with 301, so no duplicate URLs exist (M8 merges it into _redirects).
//   4. Placeholder pages (see SENTINEL in lib/i18n.ts) and helper folders are deleted.
//   5. Every HTML file gets a CSP <meta> that allows its own inline scripts by hash, and nothing else inline.
//      (Next's bootstrap and flight-data scripts differ per page, and Cloudflare _headers lines are limited to 2000
//      characters, so one header with all the hashes cannot work; the header in _headers.portal carries the rest.)
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const SENTINEL = '_none'
export const SENTINEL_PAGE = '0'

/** Inline, executable <script> bodies of a page (src scripts and JSON data blocks such as JSON-LD are not inline code). */
export function inlineScripts(html) {
  const found = []
  for (const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/g)) {
    const attrs = match[1]
    if (/\bsrc\s*=/.test(attrs)) continue
    if (/\btype\s*=\s*["']?(application\/(ld\+)?json|importmap|speculationrules)/i.test(attrs)) continue
    if (match[2].trim() === '') continue
    found.push(match[2])
  }
  return found
}

export const sha256 = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`

/** The page's CSP: own files plus exactly its own inline scripts. No 'unsafe-inline', no eval. */
export function cspFor(html) {
  const hashes = [...new Set(inlineScripts(html).map(sha256))]
  return ["default-src 'self'", `script-src 'self' ${hashes.join(' ')}`.trim()].join('; ')
}

export function withCsp(html) {
  const meta = `<meta http-equiv="Content-Security-Policy" content="${cspFor(html)}"/>`
  if (!/<head[^>]*>/.test(html)) throw new Error('no <head> to put the CSP in')
  return html.replace(/<head([^>]*)>/, (head) => `${head}${meta}`)
}

/** Cloudflare _redirects lines: the default language also exists at the root, so its prefixed copy is a permanent redirect. */
export function redirectRules(defaultLocale) {
  return `# Generated by web/portal/scripts/finalize-export.mjs; M8 merges this into the single _redirects file.\n/${defaultLocale} / 301\n/${defaultLocale}/* /:splat 301\n`
}

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) yield* walk(path)
    else yield path
  }
}

/** Removes placeholder folders (an export needs at least one param per dynamic route, a young site has none). */
function removePlaceholders(out) {
  const doomed = []
  const visit = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (!statSync(path).isDirectory()) continue
      if (name === SENTINEL || (name === SENTINEL_PAGE && basename(dir) === 'page')) doomed.push(path)
      else visit(path)
    }
  }
  visit(out)
  for (const path of doomed) rmSync(path, { recursive: true, force: true })
  return doomed.length
}

export function finalize({ out, defaultLocale }) {
  const tree = join(out, defaultLocale)
  if (!existsSync(tree)) throw new Error(`${tree} does not exist: is LOCALE_DEFAULT the same as at build time?`)

  // 1. The localised 404, rendered by the 404-source route inside the locale layout.
  const source = join(tree, '404-source', 'index.html')
  if (!existsSync(source)) throw new Error('404-source page missing from the export')
  writeFileSync(join(out, '404.html'), readFileSync(source))
  rmSync(join(out, '404'), { recursive: true, force: true })
  rmSync(join(out, '_not-found'), { recursive: true, force: true })
  rmSync(join(tree, '404-source'), { recursive: true, force: true })

  // 2. The default language moves to the root. Nothing at the root may be overwritten.
  for (const name of readdirSync(tree)) {
    const target = join(out, name)
    if (existsSync(target)) throw new Error(`cannot move ${defaultLocale}/${name}: ${name} already exists at the root of the export`)
    renameSync(join(tree, name), target)
  }
  rmSync(tree, { recursive: true, force: true })

  // 3. Redirects for the old prefixed URLs.
  writeFileSync(join(out, '_redirects.portal'), redirectRules(defaultLocale))

  // 4. Placeholders.
  const removed = removePlaceholders(out)

  // 5. Per-page CSP.
  let pages = 0
  for (const file of walk(out)) {
    if (!file.endsWith('.html')) continue
    writeFileSync(file, withCsp(readFileSync(file, 'utf8')))
    pages++
  }

  return { pages, removed }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = resolve(process.argv[2] ?? 'out')
  const { pages, removed } = finalize({ out, defaultLocale: process.env.LOCALE_DEFAULT ?? 'en' })
  console.log(`finalize-export: ${pages} pages, ${removed} placeholder folders removed, 404.html and _redirects.portal written`)
}
